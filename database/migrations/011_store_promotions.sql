-- ============================================================
-- The Blue Moon Ecommerce
-- Migration 011: Store delivery charges and promotions
-- ============================================================
--
-- Security:
--   - Delivery charge is server-side only.
--   - Promotion management uses the existing admin API.
--   - Customers never provide trusted discount/delivery totals.
--   - Checkout will calculate the final amount server-side.
--   - Pricing values are snapshotted on the order.
-- ============================================================


-- ------------------------------------------------------------
-- 1. Store settings
-- ------------------------------------------------------------

create table if not exists public.store_settings (
    id bigint primary key,

    delivery_charge numeric(12,2) not null default 100
        check (delivery_charge >= 0),

    updated_at timestamptz not null default now()
);


insert into public.store_settings (
    id,
    delivery_charge
)
values (
    1,
    100
)
on conflict (id) do nothing;


-- ------------------------------------------------------------
-- 2. Store promotions
-- ------------------------------------------------------------

create table if not exists public.store_promotions (
    id bigint generated by default as identity primary key,

    code text not null,

    name text,
    description text,

    discount_type text not null
        check (
            discount_type in (
                'percentage',
                'fixed',
                'free_delivery'
            )
        ),

    discount_value numeric(12,2) not null default 0
        check (discount_value >= 0),

    minimum_order_amount numeric(12,2)
        check (
            minimum_order_amount is null
            or minimum_order_amount >= 0
        ),

    maximum_discount_amount numeric(12,2)
        check (
            maximum_discount_amount is null
            or maximum_discount_amount >= 0
        ),

    starts_at timestamptz not null default now(),

    expires_at timestamptz,

    usage_limit integer
        check (
            usage_limit is null
            or usage_limit > 0
        ),

    usage_count integer not null default 0
        check (usage_count >= 0),

    per_customer_limit integer
        check (
            per_customer_limit is null
            or per_customer_limit > 0
        ),

    is_active boolean not null default true,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now(),

    constraint store_promotions_code_unique
        unique (code),

    constraint store_promotions_date_check
        check (
            expires_at is null
            or expires_at > starts_at
        ),

    constraint store_promotions_discount_check
        check (
            (
                discount_type = 'percentage'
                and discount_value > 0
                and discount_value <= 100
            )
            or
            (
                discount_type = 'fixed'
                and discount_value > 0
            )
            or
            (
                discount_type = 'free_delivery'
                and discount_value = 0
            )
        )
);


-- ------------------------------------------------------------
-- 3. Case-insensitive promo-code uniqueness
-- ------------------------------------------------------------

update public.store_promotions
set code = upper(trim(code));


create unique index if not exists
    idx_store_promotions_code_lower_unique
on public.store_promotions (
    lower(code)
);


-- ------------------------------------------------------------
-- 4. Promotion usage
-- ------------------------------------------------------------

create table if not exists public.store_promotion_usage (
    id bigint generated by default as identity primary key,

    promotion_id bigint not null
        references public.store_promotions(id)
        on delete restrict,

    customer_id bigint not null
        references public.customers(id)
        on delete restrict,

    order_id bigint
        references public.orders(id)
        on delete set null,

    used_at timestamptz not null default now()
);


-- ------------------------------------------------------------
-- 5. Pricing snapshot on orders
-- ------------------------------------------------------------

alter table public.orders
    add column if not exists delivery_charge numeric(12,2)
        not null default 0
        check (delivery_charge >= 0);

alter table public.orders
    add column if not exists promo_code text;

alter table public.orders
    add column if not exists promotion_id bigint
        references public.store_promotions(id)
        on delete set null;


-- ------------------------------------------------------------
-- 6. Indexes
-- ------------------------------------------------------------

create index if not exists idx_store_promotions_code
    on public.store_promotions(code);

create index if not exists idx_store_promotions_active
    on public.store_promotions(is_active);

create index if not exists idx_store_promotions_expiry
    on public.store_promotions(expires_at);

create index if not exists idx_store_promotion_usage_promotion
    on public.store_promotion_usage(promotion_id);

create index if not exists idx_store_promotion_usage_customer
    on public.store_promotion_usage(customer_id);

create index if not exists idx_store_promotion_usage_order
    on public.store_promotion_usage(order_id);

create index if not exists idx_orders_promotion
    on public.orders(promotion_id);


-- ------------------------------------------------------------
-- 7. Restrict direct client access
-- ------------------------------------------------------------

revoke all
on table public.store_settings
from public, anon, authenticated;

revoke all
on table public.store_promotions
from public, anon, authenticated;

revoke all
on table public.store_promotion_usage
from public, anon, authenticated;


grant select, insert, update, delete
on table public.store_settings
to service_role;

grant select, insert, update, delete
on table public.store_promotions
to service_role;

grant select, insert, update, delete
on table public.store_promotion_usage
to service_role;


-- ------------------------------------------------------------
-- 8. Restrict identity sequence access
-- ------------------------------------------------------------

grant usage, select
on sequence public.store_promotions_id_seq
to service_role;

grant usage, select
on sequence public.store_promotion_usage_id_seq
to service_role;
